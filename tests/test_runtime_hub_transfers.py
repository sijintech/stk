@pytest.fixture
def hub_chunks(live, monkeypatch):  # noqa: F811
    """Test-side hook in this process's Hub: records chunk offsets and finishes, and can hold one chunk."""
    uploads = live.app.state.uploads
    original_open, original_finish = uploads.open_chunk, uploads.finish
    hook = {"offsets": [], "finishes": 0, "hold_from": None, "holding": threading.Event(),
            "release": threading.Event(), "then": "proceed"}

    def open_chunk(device, upload_id, offset, length=None):
        hook["offsets"].append(offset)
        if hook["hold_from"] is not None and offset >= hook["hold_from"] and not hook["holding"].is_set():
            hook["holding"].set()
            hook["release"].wait(60)
            if hook["then"] == "drop":
                raise RuntimeError("held chunk dropped by the test")  # the dead client's request only
        return original_open(device, upload_id, offset, length)

    def finish(device, upload_id):
        hook["finishes"] += 1
        return original_finish(device, upload_id)

    monkeypatch.setattr(uploads, "open_chunk", open_chunk)
    monkeypatch.setattr(uploads, "finish", finish)
    return hook


def in_background(arguments):
    box = {}
    thread = threading.Thread(target=lambda: box.update(result=CliRunner().invoke(workspaces, arguments)), daemon=True)
    thread.start()
    return thread, box


def worker_processes():
    import psutil
    return [p for p in psutil.Process().children(recursive=True)
            if any("suan.runtime.hub_transfers" in part for part in p.cmdline())]


def wait_for(predicate, timeout=30):
    deadline = time.monotonic() + timeout
    while not predicate():
        assert time.monotonic() < deadline
        time.sleep(0.02)


def test_kill_after_hub_accepted_a_chunk_resumes_the_same_session_at_its_offset(live, desktop, source, hub_chunks):  # noqa: F811
    target, state = desktop
    workspace = live.client.create_workspace("crash")["id"]
    transfer = ht.keyed_transfer_id("crash-once")
    hub_chunks.update(hold_from=MIB, then="drop")
    thread, box = in_background(target + ["upload", workspace, str(source), "--key", "crash-once"])
    assert hub_chunks["holding"].wait(30)
    journal = json.loads(ht.journal_path(state, transfer).read_text())
    device = json.loads((state / "hubs.json").read_text())["lab"]["device_id"]
    upload_id = journal["items"][0]["upload_id"]
    held = live.app.state.uploads.status(device, upload_id)
    assert held["offset"] == MIB and held["completed"] is False  # the hub accepted the first chunk ...
    assert journal["bytes_done"] == 0 and journal["state"] == "running"  # ... the journal has no ACK of it
    # The live, blocked worker itself holds the namespace lease: second commands are busy and change nothing.
    with pytest.raises(ht.Busy):
        ht.NamespaceLease(ht.namespace(state))
    before = tree_snapshot(ht.journal_dir(state))
    for arguments in (["transfers", "resume", transfer], ["upload", workspace, str(source), "--key", "crash-once"]):
        assert value(invoke(target + arguments, code=3))["outcome"] == "busy"
    assert tree_snapshot(ht.journal_dir(state)) == before
    workers = worker_processes()
    assert len(workers) == 1
    with pytest.raises(ht.Busy):  # still held right up to the kill
        ht.NamespaceLease(ht.namespace(state))
    workers[0].kill()  # only this command's own worker (cross-platform kill, no signal constant)
    thread.join(60)
    assert not workers[0].is_running()  # really exited and reaped by the parent
    ht.NamespaceLease(ht.namespace(state)).stream.close()  # released only now, by the OS at process exit
    hub_chunks["release"].set()
    lost = value(box["result"])
    assert box["result"].exit_code == 1 and lost["outcome"] == "unknown" and lost["worker"]["exit_code"] != 0
    # No receipt: the original transfer is shown only as an observation after the reap, never as the receipt.
    assert "journal" not in lost and lost["subsequent_observation"]["transfer"]["id"] == transfer
    before = len(hub_chunks["offsets"])
    resumed = value(invoke(target + ["transfers", "resume", transfer]))
    assert resumed["outcome"] == "pending_review" and resumed["transfer_id"] == transfer
    new_offsets = hub_chunks["offsets"][before:]
    assert new_offsets[0] == MIB and 0 not in new_offsets and hub_chunks["finishes"] == 1
    after = json.loads(ht.journal_path(state, transfer).read_text())
    assert after["id"] == transfer and after["request"] == journal["request"]
    assert runtime_files(live, workspace) == {}
    approve(live, resumed["import_intent"]["action_id"])
    assert value(invoke(target + ["transfers", "resume", transfer]))["outcome"] == "completed"
    assert runtime_files(live, workspace) == {"field.bin": (len(DATA), DIGEST)}


