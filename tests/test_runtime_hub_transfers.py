def publication_temporaries(state_dir):
    return sorted(path.name for path in ht.journal_dir(state_dir).iterdir() if ".cli.tmp-" in path.name)


def unsupported_link(monkeypatch, code):
    import errno

    def link(source, destination, *args, **kwargs):
        raise OSError(getattr(errno, code), f"injected {code}")
    monkeypatch.setattr(ht.os, "link", link)


@pytest.mark.parametrize("code", ["EOPNOTSUPP", "EPERM", "ENOSYS"])
def test_an_unsupported_link_never_falls_back_to_replacing_a_sidecar_that_appears_meanwhile(tmp_path, monkeypatch,
                                                                                             code):
    """A non-participating writer (not a lease holder) creates the same transfer's sidecar in the window that the
    old ``exists()`` / ``os.replace`` fallback had. Its bytes must survive and the holder must not adopt the
    incoming identity."""
    transfer = ht.keyed_transfer_id("k")
    ht.journal_dir(tmp_path).mkdir(parents=True)
    final = ht.sidecar_path(tmp_path, transfer)
    rival = ht.canonical(sample_sidecar(transfer, source="/rival"))
    replaced, real_replace = [], ht.os.replace

    def replace(source, destination, *args, **kwargs):
        if Path(destination) == final:
            final.write_bytes(rival)  # the other writer wins the window after exists() saw nothing
            replaced.append(destination)
        return real_replace(source, destination, *args, **kwargs)

    unsupported_link(monkeypatch, code)
    monkeypatch.setattr(ht.os, "replace", replace)
    holder = ht.SidecarHolder(tmp_path, transfer)
    try:
        holder.publish(sample_sidecar(transfer))
        refusal = None
    except ht.Refused as exc:
        refusal = exc.reason
    present = final.read_bytes() if final.exists() else None
    assert present in (None, rival), "the other writer's sidecar was replaced by the incoming bytes"
    assert holder.sidecar is None, "the holder adopted the incoming identity"
    assert refusal == "sidecar_publication_unsupported" and replaced == []
    assert publication_temporaries(tmp_path) == []
    final.unlink(missing_ok=True)
    final.write_bytes(rival)  # the other writer's sidecar is present now; a retry must leave it alone
    with pytest.raises(ht.Refused, match="sidecar_publication_unsupported"):
        holder.publish(sample_sidecar(transfer))
    assert final.read_bytes() == rival and replaced == [] and holder.sidecar is None
    assert publication_temporaries(tmp_path) == []


def test_an_unsupported_link_with_no_sidecar_refuses_and_leaves_nothing(tmp_path, monkeypatch):
    transfer = ht.keyed_transfer_id("k")
    ht.journal_dir(tmp_path).mkdir(parents=True)
    unsupported_link(monkeypatch, "EOPNOTSUPP")
    holder = ht.SidecarHolder(tmp_path, transfer)
    with pytest.raises(ht.Refused, match="sidecar_publication_unsupported"):
        holder.publish(sample_sidecar(transfer))
    assert not ht.sidecar_path(tmp_path, transfer).exists() and holder.sidecar is None
    assert sorted(path.name for path in ht.journal_dir(tmp_path).iterdir()) == []


def test_a_real_hard_link_publishes_once_and_never_overwrites(tmp_path):
    """Control: the atomic no-overwrite primitive stays usable, and an existing final sidecar keeps its bytes."""
    transfer = ht.keyed_transfer_id("k")
    ht.journal_dir(tmp_path).mkdir(parents=True)
    final = ht.sidecar_path(tmp_path, transfer)
    first = ht.SidecarHolder(tmp_path, transfer)
    first.publish(sample_sidecar(transfer))
    original = final.read_bytes()
    assert original == ht.canonical(sample_sidecar(transfer)) and first.sidecar == sample_sidecar(transfer)
    assert final.stat().st_nlink == 1 and publication_temporaries(tmp_path) == []
    second = ht.SidecarHolder(tmp_path, transfer)
    with pytest.raises(ht.Refused, match="sidecar_exists"):
        second.publish(sample_sidecar(transfer, source="/other"))
    assert final.read_bytes() == original and second.sidecar is None and publication_temporaries(tmp_path) == []


def test_an_existing_sidecar_keeps_its_bytes_when_the_link_is_unsupported(tmp_path, monkeypatch):
    """Control: an already present final sidecar is refused over (old and new code alike) and stays unchanged."""
    transfer = ht.keyed_transfer_id("k")
    ht.journal_dir(tmp_path).mkdir(parents=True)
    final = ht.sidecar_path(tmp_path, transfer)
    existing = ht.canonical(sample_sidecar(transfer, source="/existing"))
    final.write_bytes(existing)
    unsupported_link(monkeypatch, "EOPNOTSUPP")
    holder = ht.SidecarHolder(tmp_path, transfer)
    with pytest.raises(ht.Refused):
        holder.publish(sample_sidecar(transfer))
    assert final.read_bytes() == existing and holder.sidecar is None and publication_temporaries(tmp_path) == []


