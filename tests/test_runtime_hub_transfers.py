def runtime_files(live, workspace):  # noqa: F811
    return {f["path"]: (f["size"], f["sha256"]) for f in live.client.files(workspace)}


def approve(live, action_id, approved=True):  # noqa: F811
    response = live.http.post(f"/api/v1/actions/{action_id}/review", json={"approved": approved}, headers=AUTH)
    assert response.status_code == 200, response.text


def tree_snapshot(root):
    return {str(p.relative_to(root)): (p.stat().st_mtime_ns, p.read_bytes()) for p in sorted(root.rglob("*"))
            if p.is_file()}


def test_upload_waits_for_review_then_explicit_resume_completes_the_original(live, desktop, source):  # noqa: F811
    target, state = desktop
    workspace = live.client.create_workspace("CLI inputs")["id"]
    transfer = ht.keyed_transfer_id("cli-upload")
    started = invoke(target + ["upload", workspace, str(source), "--key", "cli-upload"])
    # The original key and transfer ID are printed before the worker runs.
    assert started.stderr.index("Idempotency key: cli-upload") < started.stderr.index(f"Transfer: {transfer}")
    receipt = value(started)
    assert receipt["outcome"] == "pending_review" and receipt["observed_from"] == "worker_receipt"
    assert receipt["observed_at"] and receipt["transfer_id"] == transfer and receipt["threads_alive"] is False
    assert receipt["worker"]["forced"] is False and receipt["worker"]["exit_code"] == 0
    intent = receipt["import_intent"]
    assert intent["attempt"] == 0 and receipt["journal"]["action"] == {"id": intent["action_id"], "state": "review"}
    # The fixture holds the approval: before it, the workspace has no file and no task.
    assert runtime_files(live, workspace) == {} and live.client.tasks() == []
    lease = ht.namespace(state) / "namespace.lock"
    assert lease.exists()
    ht.NamespaceLease(ht.namespace(state)).stream.close()  # the worker's lease ended with its process
    approve(live, intent["action_id"])
    done = value(invoke(target + ["transfers", "resume", transfer]))
    assert done["outcome"] == "completed" and done["journal"]["action"]["state"] == "succeeded"
    assert done["import_intent"] == intent  # the same original action, not a new one
    checked = value(invoke(target + ["transfers", "show", transfer, "--check"]))
    assert checked["check"]["matches_intent"] is True and checked["check"]["action"]["state"] == "succeeded"
    assert runtime_files(live, workspace) == {"field.bin": (len(DATA), DIGEST)}
    target_file = Path(live.client.download_input(workspace, "field.bin", state / "check.bin"))
    assert target_file.read_bytes() == DATA
    # The same key returns the original transfer; another request under the key is a conflict.
    sidecar = ht.sidecar_path(state, transfer).read_bytes()
    again = value(invoke(target + ["upload", workspace, str(source), "--key", "cli-upload"]))
    assert again["outcome"] == "completed" and again["transfer_id"] == transfer
    conflict = value(invoke(target + ["upload", workspace, str(source), "--key", "cli-upload", "--path", "other.bin"],
                            code=1))
    assert conflict["outcome"] == "conflict" and ht.sidecar_path(state, transfer).read_bytes() == sidecar
    assert len(live.actions("workspace.import")) == 1


