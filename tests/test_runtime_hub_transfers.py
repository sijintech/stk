IGNORES_TERM = ("import signal, sys, time; signal.signal(signal.SIGTERM, signal.SIG_IGN); "
                "sys.stdout.write('ready\\n'); sys.stdout.flush(); time.sleep(30)")


@pytest.mark.skipif(os.name == "nt", reason="SIGTERM cannot be ignored on Windows")
@pytest.mark.parametrize("method,interrupts", [
    ("kill", 1),        # the exact boundary: the interrupt lands before the kill signal was sent
    ("kill", 3),        # repeated before every kill attempt
    ("terminate", 2),   # before the terminate signal was sent
    ("wait", 1),        # in the settle wait after terminate (escalates to kill)
    ("wait", 4),        # in the settle waits after terminate and after kill
    ("poll", 3),        # in the first polls of the reap
])
def test_reap_retries_a_signal_an_interrupt_prevented_and_never_waits_untimed(monkeypatch, method, interrupts):
    """An owned stub that ignores SIGTERM and would otherwise live 30 s: an interrupt before a signal call ran
    must retry that call, and the reap must end with the real SIGKILL exit, never in an untimed wait."""
    import signal
    import subprocess
    import sys
    monkeypatch.setattr(ht, "KILL_GRACE", 0.3)
    child = subprocess.Popen([sys.executable, "-c", IGNORES_TERM], stdout=subprocess.PIPE)
    try:
        assert child.stdout.readline() == b"ready\n"  # SIGTERM is ignored from here on
        real = {name: getattr(child, name) for name in ("kill", "terminate", "wait", "poll")}
        calls = {name: 0 for name in real}

        def wrap(name):
            def call(*args, **kwargs):
                calls[name] += 1
                if name == "wait" and kwargs.get("timeout", args[0] if args else None) is None:
                    raise AssertionError("an untimed wait in the reap")
                if name == method and calls[name] <= interrupts:
                    raise KeyboardInterrupt  # delivered before the real operation ran
                return real[name](*args, **kwargs)
            return call

        for name in real:
            setattr(child, name, wrap(name))
        started = time.monotonic()
        forced = ht._reap(child)
        elapsed = time.monotonic() - started
        for name in real:
            setattr(child, name, real[name])
        assert forced is True and child.returncode == -signal.SIGKILL, (calls, child.returncode)
        assert elapsed < 5, elapsed
        if method in ("kill", "terminate"):
            assert calls[method] > interrupts  # the prevented call was really made afterwards
    finally:
        for name in ("kill", "terminate", "wait", "poll"):
            child.__dict__.pop(name, None)
        if child.poll() is None:  # only our own tracked stub; a red case could leave it alive
            child.kill()
            child.wait()
        child.stdout.close()


