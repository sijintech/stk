def test_an_interrupt_at_any_poll_of_the_supervisor_or_reap_still_reaps_the_owned_child(monkeypatch, interrupted_poll):
    """A first interrupt lands in the supervisor's wait; a second at the N-th poll (supervisor loop, the reap's
    first poll, the settle loops). The owned stub child is reaped every time and the call returns."""
